"""M2 / step 1 of PLAN-MORAL-1120 (MoraleInProgress.md): the C++ copy of the morale table is the one make_effects.py writes from Effects.csv.

Relations only, read from the real CSV (no number is copied here): the header Source/HeroesOfLiberty/Simulation/HOLMoraleTableRows.h has one
constexpr row per CSV row, in the CSV's order, and every field read back from that header equals the CSV's own value (a Gives name is the
index of the row it names, -1 when empty; Sign Malus and Form Aura and Attenuable True become booleans); the file on disk is the one the
generator would write now (make_effects.py --check exits 0).

  python Tools/Data/make_effects_test.py      prints one line per failed check and PASS / FAIL; exit code 0 / 1
"""
import os
import re
import subprocess
import sys

DATA = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, DATA)
import make_effects  # noqa: E402


def parse_rows(text):
    """Reads every `{ ... }` row line of the generated header back into a dict (the test's own parser, independent of the writer)."""
    rows = []
    for m in re.finditer(r'^\s*\{\s*"(?P<key>[A-Za-z0-9_]+)",\s*(?P<malus>true|false),\s*(?P<dealt>-?\d+),\s*(?P<taken>-?\d+),\s*(?P<rate>-?\d+),\s*'
                         r'(?P<aura>true|false),\s*(?P<dur>\d+),\s*(?P<radius>\d+),\s*(?P<gives>-?\d+),\s*(?P<att>true|false)\s*\},?\s*$',
                         text, re.MULTILINE):
        rows.append(m.groupdict())
    return rows


def main():
    problems = []
    checks = [0]

    def check(ok, text):
        checks[0] += 1
        if not ok:
            problems.append(text)

    csv_rows = make_effects.load()
    names = [r["Name"] for r in csv_rows]
    text = make_effects.render_cpp(csv_rows)
    check(len(text) > 0, "render_cpp writes nothing")
    check(text.startswith("// GENERATED by Tools/Data/make_effects.py"), "the header does not say it is generated")
    got = parse_rows(text)
    check(len(got) == len(csv_rows), f"{len(got)} rows in the header, {len(csv_rows)} in the CSV")
    count = re.search(r"constexpr int HOLMoraleRowCount = (\d+);", text)
    check(count is not None and int(count.group(1)) == len(csv_rows), "HOLMoraleRowCount is not the number of CSV rows")
    for i, (r, g) in enumerate(zip(csv_rows, got)):
        n = r["Name"]
        check(g["key"] == n, f"row {i}: key {g['key']} is not {n}")
        check((g["malus"] == "true") == (r["Sign"] == "Malus"), f"{n}: sign")
        check(int(g["dealt"]) == int(r["Dealt"]), f"{n}: Dealt")
        check(int(g["taken"]) == int(r["Taken"]), f"{n}: Taken")
        check(int(g["rate"]) == int(r["Rate"]), f"{n}: Rate")
        check((g["aura"] == "true") == (r["Form"] == "Aura"), f"{n}: form")
        check(int(g["dur"]) == int(r["DurationMs"]), f"{n}: DurationMs")
        check(int(g["radius"]) == int(r["RadiusCm"]), f"{n}: RadiusCm")
        want_gives = names.index(r["Gives"]) if r["Gives"] else -1
        check(int(g["gives"]) == want_gives, f"{n}: Gives")
        check((g["att"] == "true") == (r["Attenuable"] == "True"), f"{n}: Attenuable")
        check(re.search(rf"constexpr int HOLMorale{n} = {i};", text) is not None, f"{n}: id constant is not the row index {i}")

    result = subprocess.run([sys.executable, "-I", os.path.join(DATA, "make_effects.py"), "--check"], capture_output=True, text=True)
    check(result.returncode == 0, "make_effects.py --check: " + (result.stdout.strip() or result.stderr.strip()))

    for p in problems:
        print("FAIL: " + p)
    print(f"{'FAIL' if problems else 'PASS'} ({checks[0] - len(problems)}/{checks[0]})")
    sys.exit(1 if problems else 0)


if __name__ == "__main__":
    main()
