"""Writes Script/Morale/HOLMoraleTable.as from Tools/Data/Effects.csv (MoraleInProgress.md M2, D708).

The CSV is the table of the morale effects (one row per effect); the script cannot read a file, so this makes its copy.
Run it again whenever the CSV changes:  python Tools/Data/make_effects.py
Check that the script is in step (exit code 1 if not):  python Tools/Data/make_effects.py --check

Columns: Name (stable key), DisplayName (French, the source text of the localisation), Sign (Bonus / Malus), Dealt / Taken / Rate (signed
"benefit" percents: positive helps the unit, on the damage taken +25 means 25 % less taken), Form (Temporary: DurationMs; Aura: lasts while in
range, DurationMs is the time a planted source stands, 0 = its own life), RadiusCm (reach of the source), SourceKind (Hero, HeroCry, Banner, Duel),
Gives (the effect a source gives instead of its own levers: the Banner gives the Dawn Aura, so the two never add up), Attenuable (a malus the
Luminous Monk and Discipline of the Dawn can attenuate), Description (French).
"""
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CSV_PATH = ROOT / "Tools" / "Data" / "Effects.csv"
OUT_PATH = ROOT / "Script" / "Morale" / "HOLMoraleTable.as"


def q(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def load():
    with open(CSV_PATH, encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


def render(rows):
    keys = [r["Name"] for r in rows]
    out = []
    out.append("// GENERATED by Tools/Data/make_effects.py from Tools/Data/Effects.csv: do not edit by hand (MoraleInProgress.md M2, D708).")
    out.append("// The table of the morale effects, one row per effect; HOLMoraleTable_Test.as checks its coherence. Percents are the signed benefit percents of")
    out.append("// HOLMoraleRules.as. Ids are the CSV's row order.")
    out.append("namespace HOLMoraleTable")
    out.append("{")
    out.append(f"\tconst int Count = {len(rows)};")
    for i, k in enumerate(keys):
        out.append(f"\tconst int {k} = {i};")
    out.append("")
    out.append("\t// One row of the table.")
    out.append("\tstruct FHOLMoraleRow")
    out.append("\t{")
    out.append("\t\tFString Key;")
    out.append("\t\tbool bMalusSign = false;")
    out.append("\t\tint Dealt = 0;")
    out.append("\t\tint Taken = 0;")
    out.append("\t\tint Rate = 0;")
    out.append("\t\tbool bAura = false;")
    out.append("\t\tint DurationMs = 0;")
    out.append("\t\tint RadiusCm = 0;")
    out.append("\t\tFString SourceKind;")
    out.append("\t\tint Gives = -1;")
    out.append("\t\tbool bAttenuable = false;")
    out.append("\t}")
    out.append("")
    out.append("\t// The row of an id (an empty row, Key empty, for an id out of the table).")
    out.append("\tFHOLMoraleRow Row(int Id)")
    out.append("\t{")
    out.append("\t\tFHOLMoraleRow R;")
    for i, r in enumerate(rows):
        gives = keys.index(r["Gives"]) if r["Gives"] else -1
        out.append(f"\t\tif (Id == {i})")
        out.append("\t\t{")
        out.append(f"\t\t\tR.Key = {q(r['Name'])};")
        out.append(f"\t\t\tR.bMalusSign = {'true' if r['Sign'] == 'Malus' else 'false'};")
        out.append(f"\t\t\tR.Dealt = {int(r['Dealt'])};")
        out.append(f"\t\t\tR.Taken = {int(r['Taken'])};")
        out.append(f"\t\t\tR.Rate = {int(r['Rate'])};")
        out.append(f"\t\t\tR.bAura = {'true' if r['Form'] == 'Aura' else 'false'};")
        out.append(f"\t\t\tR.DurationMs = {int(r['DurationMs'])};")
        out.append(f"\t\t\tR.RadiusCm = {int(r['RadiusCm'])};")
        out.append(f"\t\t\tR.SourceKind = {q(r['SourceKind'])};")
        out.append(f"\t\t\tR.Gives = {gives};")
        out.append(f"\t\t\tR.bAttenuable = {'true' if r['Attenuable'] == 'True' else 'false'};")
        out.append("\t\t\treturn R;")
        out.append("\t\t}")
    out.append("\t\treturn R;")
    out.append("\t}")
    out.append("")
    for fn, col in (("Name", "DisplayName"), ("Description", "Description")):
        out.append(f"\tFText {fn}(int Id)")
        out.append("\t{")
        for i, r in enumerate(rows):
            out.append(f"\t\tif (Id == {i}) return NSLOCTEXT(\"HOLMoraleTable\", {q(fn + r['Name'])}, {q(r[col])});")
        out.append("\t\treturn FText();")
        out.append("\t}")
        out.append("")
    out.append("\t// The effect a row poses on a unit: its own levers, or those of the effect it gives (the Banner gives the Dawn Aura).")
    out.append("\tHOLMorale::FHOLMoraleEffect Effect(int Id)")
    out.append("\t{")
    out.append("\t\tFHOLMoraleRow R = Row(Id);")
    out.append("\t\tint EffectId = Id;")
    out.append("\t\tif (R.Gives >= 0)")
    out.append("\t\t{")
    out.append("\t\t\tEffectId = R.Gives;")
    out.append("\t\t\tR = Row(R.Gives);")
    out.append("\t\t}")
    out.append("\t\treturn HOLMorale::MakeEffect(EffectId, R.Dealt, R.Taken, R.Rate, R.DurationMs, R.bAura);")
    out.append("\t}")
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    text = render(load())
    if "--check" in sys.argv:
        current = OUT_PATH.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT_PATH.exists() else ""
        if current != text:
            print("HOLMoraleTable.as is not in step with Effects.csv: run python Tools/Data/make_effects.py")
            sys.exit(1)
        print("HOLMoraleTable.as is in step with Effects.csv")
        return
    OUT_PATH.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT_PATH} ({len(load())} effects)")


if __name__ == "__main__":
    main()
