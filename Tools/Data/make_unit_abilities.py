"""Writes Script/Units/HOLUnitAbilityTable.as from Tools/Data/UnitAbilities.csv (LegionsInProgress.md L4 step 4, the unit abilities frame, LQ-3 / D678).

The CSV is the table of the abilities a unit can be ordered to use (one row per ability); the script cannot read a file, so this makes its copy.
Run it again whenever the CSV changes:  python Tools/Data/make_unit_abilities.py
Check that the script is in step (exit code 1 if not):  python Tools/Data/make_unit_abilities.py --check

Columns: Name (stable key), DisplayName and Description (French, the source text of the localisation), UnitType (the unit type that has the
ability), Faction, Effect (the row of Effects.csv the ability lays on the unit: the levers come from the morale table, not from here),
CooldownMs (from the start of the effect), DurationMs (the time of the effect, the same as its Effects.csv row), HpCostPerHit (hit points paid
for each blow dealt while the effect lasts), MinHp (the ability is refused below it), StopHp (the effect stops when the unit would go below it:
the ability never kills).
"""
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CSV_PATH = ROOT / "Tools" / "Data" / "UnitAbilities.csv"
OUT_PATH = ROOT / "Script" / "Units" / "HOLUnitAbilityTable.as"


def q(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def load():
    with open(CSV_PATH, encoding="utf-8-sig", newline="") as f:
        return list(csv.DictReader(f))


def render(rows):
    out = []
    out.append("// GENERATED by Tools/Data/make_unit_abilities.py from Tools/Data/UnitAbilities.csv: do not edit by hand (LegionsInProgress.md L4 step 4).")
    out.append("// The table of the unit abilities, one row per ability; HOLUnitAbilityRules_Test.as checks its coherence. Ids are the CSV's row order.")
    out.append("namespace HOLUnitAbilityTable")
    out.append("{")
    out.append(f"\tconst int Count = {len(rows)};")
    for i, r in enumerate(rows):
        out.append(f"\tconst int {r['Name']} = {i};")
    out.append("")
    out.append("\t// One row of the table.")
    out.append("\tstruct FHOLUnitAbilityRow")
    out.append("\t{")
    out.append("\t\tFString Key;")
    out.append("\t\tFString UnitType;")
    out.append("\t\tFString Faction;")
    out.append("\t\tFString Effect;")
    out.append("\t\tint CooldownMs = 0;")
    out.append("\t\tint DurationMs = 0;")
    out.append("\t\tint HpCostPerHit = 0;")
    out.append("\t\tint MinHp = 0;")
    out.append("\t\tint StopHp = 0;")
    out.append("\t}")
    out.append("")
    out.append("\t// The row of an id (an empty row, Key empty, for an id out of the table).")
    out.append("\tFHOLUnitAbilityRow Row(int Id)")
    out.append("\t{")
    out.append("\t\tFHOLUnitAbilityRow R;")
    for i, r in enumerate(rows):
        out.append(f"\t\tif (Id == {i})")
        out.append("\t\t{")
        out.append(f"\t\t\tR.Key = {q(r['Name'])};")
        out.append(f"\t\t\tR.UnitType = {q(r['UnitType'])};")
        out.append(f"\t\t\tR.Faction = {q(r['Faction'])};")
        out.append(f"\t\t\tR.Effect = {q(r['Effect'])};")
        out.append(f"\t\t\tR.CooldownMs = {int(r['CooldownMs'])};")
        out.append(f"\t\t\tR.DurationMs = {int(r['DurationMs'])};")
        out.append(f"\t\t\tR.HpCostPerHit = {int(r['HpCostPerHit'])};")
        out.append(f"\t\t\tR.MinHp = {int(r['MinHp'])};")
        out.append(f"\t\t\tR.StopHp = {int(r['StopHp'])};")
        out.append("\t\t\treturn R;")
        out.append("\t\t}")
    out.append("\t\treturn R;")
    out.append("\t}")
    out.append("")
    for fn, col in (("Name", "DisplayName"), ("Description", "Description")):
        out.append(f"\tFText {fn}(int Id)")
        out.append("\t{")
        for i, r in enumerate(rows):
            out.append(f"\t\tif (Id == {i}) return NSLOCTEXT(\"HOLUnitAbilityTable\", {q(fn + r['Name'])}, {q(r[col])});")
        out.append("\t\treturn FText();")
        out.append("\t}")
        out.append("")
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    text = render(load())
    if "--check" in sys.argv:
        current = OUT_PATH.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT_PATH.exists() else ""
        if current != text:
            print("HOLUnitAbilityTable.as is not in step with UnitAbilities.csv: run python Tools/Data/make_unit_abilities.py")
            sys.exit(1)
        print("HOLUnitAbilityTable.as is in step with UnitAbilities.csv")
        return
    OUT_PATH.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT_PATH} ({len(load())} abilities)")


if __name__ == "__main__":
    main()
