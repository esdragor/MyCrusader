"""B3 (BiomeInProgress.md): the golden numbers of the Angelscript port of the map recipes' generic decor (Script/Biomes/HOLDecorRules.as),
drawn from the PYTHON it is ported from (Tools/Editor/maps/common.py: mix_seed, Rng, Noise, decor_transforms), without the editor
(stand-in `unreal`, maps_stub.py). The script never writes into Tools/Editor/maps: it only imports it.
  python Tools/Tests/biome_decor_golden.py            prints the block
  python Tools/Tests/biome_decor_golden.py --write    puts the block between the GOLDEN markers of Script/Biomes/HOLDecorRules_Test.as
  python Tools/Tests/biome_decor_golden.py --check    exit 0 if the test file holds exactly this block (the Python did not drift), 1 if not
"""
import os
import sys
import types

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import maps_stub  # noqa: E402

ROOT = maps_stub.install()
from maps import common  # noqa: E402

TEST_FILE = os.path.join(ROOT, "Script", "Biomes", "HOLDecorRules_Test.as")
BEGIN = "// GOLDEN BEGIN (generated by Tools/Tests/biome_decor_golden.py --write from maps/common.py; never edit by hand)"
END = "// GOLDEN END"

MIX_CASES = [(1, 71, 3), (7, 72, 3), (-5, 2), (123456789, 0, 4294967295)]
RNG_SEED = (7, 71, 3)
RNG_COUNT = 6
NOISE_SEED = (7, 72, 3)
NOISE_PROBES = [(0.0, 0.0), (1234.5, -6789.0), (-15000.0, 12000.0), (19999.0, 19999.0)]
AVOID = [(0.0, 0.0), (5000.0, 0.0), (-5000.0, 3000.0), (12000.0, -12000.0), (-15000.0, -15000.0), (800.0, 800.0), (-9000.0, 9000.0), (16000.0, 15000.0),
         (2500.0, -7000.0), (-1200.0, -300.0)]
# layout_seed, bounds_half, per_hectare, salt: a plain map; then a small crowded one where many tries are refused.
CASES = [(7, 20000.0, 150.0, 3), (31, 6000.0, 400.0, 9)]


def d(value):
    return repr(float(value))


def build():
    lines = [BEGIN]
    lines.append("TArray<uint> GoldenMixSeeds()\n{\n\tTArray<uint> R;")
    for case in MIX_CASES:
        lines.append(f"\tR.Add({common.mix_seed(*case)});  // MixSeed of {case}")
    lines.append("\treturn R;\n}\n")
    lines.append("TArray<int64> GoldenMixInputs(int Which)\n{\n\tTArray<int64> R;")
    lines.append("\tif (Which == 0) { R.Add(1); R.Add(71); R.Add(3); }")
    lines.append("\telse if (Which == 1) { R.Add(7); R.Add(72); R.Add(3); }")
    lines.append("\telse if (Which == 2) { R.Add(-5); R.Add(2); }")
    lines.append("\telse { R.Add(123456789); R.Add(0); R.Add(4294967295); }")
    lines.append("\treturn R;\n}\n")
    rng = common.Rng(*RNG_SEED)
    lines.append("// The first draws of Rng(7, 71, 3).\nTArray<uint> GoldenRngStream()\n{\n\tTArray<uint> R;")
    for _ in range(RNG_COUNT):
        lines.append(f"\tR.Add({rng.next_u32()});")
    lines.append("\treturn R;\n}\n")
    rng = common.Rng(*RNG_SEED)
    lines.append("// The first uniform draws of the same stream.\nTArray<double> GoldenRngUniforms()\n{\n\tTArray<double> R;")
    for _ in range(RNG_COUNT):
        lines.append(f"\tR.Add({d(rng.uniform())});")
    lines.append("\treturn R;\n}\n")
    noise = common.Noise(common.mix_seed(*NOISE_SEED[:2], NOISE_SEED[2]), waves=3, shortest=2500.0, longest=9000.0)
    lines.append("// Noise(MixSeed(7, 72, 3), 3 waves, 2500..9000) at the probes.\nTArray<FVector2D> GoldenNoiseProbes()\n{\n\tTArray<FVector2D> R;")
    for x, y in NOISE_PROBES:
        lines.append(f"\tR.Add(FVector2D({d(x)}, {d(y)}));")
    lines.append("\treturn R;\n}\n")
    lines.append("TArray<double> GoldenNoiseValues()\n{\n\tTArray<double> R;")
    for x, y in NOISE_PROBES:
        lines.append(f"\tR.Add({d(noise.value(x, y))});")
    lines.append("\treturn R;\n}\n")
    lines.append("TArray<FVector2D> GoldenAvoid()\n{\n\tTArray<FVector2D> R;")
    for x, y in AVOID:
        lines.append(f"\tR.Add(FVector2D({d(x)}, {d(y)}));")
    lines.append("\treturn R;\n}\n")
    lines.append("// decor_transforms of the cases: the inputs, the count, the first four and the last place, the sums.\nFHOLDecorGolden GoldenCase(int Which)\n{")
    lines.append("\tFHOLDecorGolden G;")
    for index, (seed, half, per_hectare, salt) in enumerate(CASES):
        recipe = types.SimpleNamespace(layout_seed=seed, bounds_half=half)
        places = common.decor_transforms(recipe, AVOID, per_hectare, salt)
        flat = [value for place in places[:4] for value in place]
        last = list(places[-1])
        lines.append(f"\t{'if' if index == 0 else 'else if'} (Which == {index})\n\t{{")
        lines.append(f"\t\tG.LayoutSeed = {seed};\n\t\tG.Half = {d(half)};\n\t\tG.PerHectare = {d(per_hectare)};\n\t\tG.Salt = {salt};")
        lines.append(f"\t\tG.Count = {len(places)};")
        lines.append("\t\t" + " ".join(f"G.First.Add({d(v)});" for v in flat))
        lines.append("\t\t" + " ".join(f"G.Last.Add({d(v)});" for v in last))
        lines.append(f"\t\tG.SumX = {d(sum(p[0] for p in places))};\n\t\tG.SumY = {d(sum(p[1] for p in places))};")
        lines.append(f"\t\tG.SumTurn = {d(sum(p[2] for p in places))};\n\t\tG.SumSize = {d(sum(p[3] for p in places))};")
        lines.append("\t}")
    lines.append("\treturn G;\n}")
    lines.append(END)
    return "\n".join(lines) + "\n"


def splice(text, block):
    start = text.index(BEGIN)
    stop = text.index(END) + len(END) + 1
    return text[:start] + block + text[stop:]


def main():
    block = build()
    if "--write" in sys.argv or "--check" in sys.argv:
        with open(TEST_FILE, encoding="utf-8", newline="") as handle:
            text = handle.read()
        newline = "\r\n" if "\r\n" in text else "\n"
        text = text.replace("\r\n", "\n")
        updated = splice(text, block)
        if "--check" in sys.argv:
            print("PASS: the test file holds the Python's golden block" if updated == text else "FAIL: the golden block drifted from maps/common.py")
            return 0 if updated == text else 1
        with open(TEST_FILE, "w", encoding="utf-8", newline="") as handle:
            handle.write(updated.replace("\n", newline))
        print("written", TEST_FILE)
        return 0
    sys.stdout.write(block)
    return 0


if __name__ == "__main__":
    sys.exit(main())
