# B3 (BiomeInProgress.md), densities of the generic biome decor per map, per size and per layout seed, read on the REAL chain:
# for each (map, size) one scenario (written here, run by Tools\Scenarios\check.ps1) lays the decor of every biome for layout seeds
# 1, 2, 3 (hol.Biome.LayoutSeed, then hol.Biome.Index -1 to take the old decor away, then hol.Biome.Index 0..4) and the journal
# carries, in order, "Biome decor expect: pieces= kinds= half= seed=" (the plan the applier laid) and "Biome decor world:" (what the
# MONDE holds, hol.Biome.DecorWorld). PASS only if, for every map: 15 plans came (3 seeds x 5 biomes), each says the seed that was
# asked (the knob acts), and the world holds as many pieces as the plan said. Prints a table and writes
# Saved_Tests\Logs\biome_decor_density.txt. ~1 min per map and size, an editor off screen each (never two scripts at once).
#   powershell -ExecutionPolicy Bypass -File Tools\Tests\biome_decor_density.ps1 [-Root <worktree>] [-Jobs "Plain:Small,Cols:Normal"]
param(
    [string] $Root = "",
    [string] $Jobs = ""
)
if (-not $Root) { $Root = Resolve-Path "$PSScriptRoot\..\.." }
$Root = (Resolve-Path $Root).Path
if (-not $Jobs) {
    $List = @()
    foreach ($Map in "Plain", "Cols", "Crown", "ElDorado", "Fords", "Forest", "Hinterland", "Steppe") { $List += "${Map}:Normal"; $List += "${Map}:Huge" }
    $List += "Plain:Small", "Plain:Medium", "Plain:Large"
    $Jobs = $List -join ","
}
$Biomes = "fresh_grass", "dry_steppe", "autumn", "dark_forest", "snow"
$Seeds = 1, 2, 3
$Fails = 0
$Rows = @()
$Dir = Join-Path $Root "Tools\Scenarios"
foreach ($Job in $Jobs.Split(",")) {
    $Map, $Size = $Job.Split(":")
    $Name = "biome_density_${Map}_${Size}".ToLower()
    $Json = '{ "map": "/Game/Maps/' + $Map + '.' + $Map + '", "mapSize": "' + $Size + '", "bDrawPlaces": false, "startingPeasants": 0, "startingHero": 0, "slots": [ { "state": "Human", "colorIndex": 0, "team": 1 }, { "state": "AI", "colorIndex": 1, "team": 2 } ] }'
    $Text = @("# Generated by biome_decor_density.ps1 (deleted at the end): decor densities of $Map $Size.", "frames 90")
    foreach ($Seed in $Seeds) {
        $Text += "hol.Biome.LayoutSeed $Seed"
        $Text += "hol.Biome.Index -1"
        $Text += "frames 30"
        for ($K = 0; $K -lt 5; $K++) { $Text += "hol.Biome.Index $K"; $Text += "frames 45"; $Text += "hol.Biome.DecorWorld" }
    }
    $Text += "note densities read"
    Set-Content -Path (Join-Path $Dir "$Name.json") -Value $Json -Encoding ASCII
    Set-Content -Path (Join-Path $Dir "$Name.txt") -Value $Text -Encoding ASCII
    try {
        & powershell -ExecutionPolicy Bypass -File (Join-Path $Dir "check.ps1") $Name -Root $Root | Out-Null
    } finally {
        Remove-Item (Join-Path $Dir "$Name.json"), (Join-Path $Dir "$Name.txt") -ErrorAction SilentlyContinue
    }
    $Log = Join-Path $Root "Saved_Tests\Logs\scenario_$Name.log"
    $Lines = if (Test-Path $Log) { Get-Content $Log } else { @() }
    $Expect = @($Lines | Where-Object { $_ -match 'Biome decor expect:' })
    $World = @($Lines | Where-Object { $_ -match 'Biome decor world:' })
    if ($Expect.Count -ne 15 -or $World.Count -ne 15) { Write-Host "FAIL $Job : $($Expect.Count) plans and $($World.Count) world readings, expected 15 each"; $Fails++; continue }
    $Index = 0
    foreach ($Seed in $Seeds) {
        for ($K = 0; $K -lt 5; $K++) {
            $E = [regex]::Match($Expect[$Index], 'pieces=(\d+) kinds=(\d+) half=(\d+) seed=(\d+)')
            $W = [regex]::Match($World[$Index], 'pieces=(\d+)')
            if (-not $E.Success) { Write-Host "FAIL $Job seed $Seed $($Biomes[$K]) : the plan line carries no seed: $($Expect[$Index])"; $Fails++; $Index++; continue }
            $Pieces = [int]$E.Groups[1].Value; $Half = [int]$E.Groups[3].Value
            if ([int]$E.Groups[4].Value -ne $Seed) { Write-Host "FAIL $Job $($Biomes[$K]) : asked seed $Seed, the plan used $($E.Groups[4].Value)"; $Fails++ }
            if ([int]$W.Groups[1].Value -ne $Pieces) { Write-Host "FAIL $Job seed $Seed $($Biomes[$K]) : the plan said $Pieces pieces, the world holds $($W.Groups[1].Value)"; $Fails++ }
            $Hectares = ([double](2 * $Half) / 100.0) * ([double](2 * $Half) / 100.0) / 10000.0
            $Rows += [pscustomobject]@{ Map = $Map; Size = $Size; Half = $Half; Seed = $Seed; Biome = $Biomes[$K]; Pieces = $Pieces; Kinds = [int]$E.Groups[2].Value; PerHa = [math]::Round($Pieces / [math]::Max($Hectares, 0.0001), 1) }
            $Index++
        }
    }
    Write-Host "read $Job : half $Half cm, $([int]($Rows | Where-Object { $_.Map -eq $Map -and $_.Size -eq $Size -and $_.Seed -eq 1 } | Measure-Object Pieces -Sum).Sum) pieces over the 5 biomes (seed 1)"
}
$Out = Join-Path $Root "Saved_Tests\Logs\biome_decor_density.txt"
$Table = $Rows | Format-Table Map, Size, Half, Seed, Biome, Pieces, Kinds, PerHa -AutoSize | Out-String -Width 200
Set-Content -Path $Out -Value $Table -Encoding UTF8
Write-Host $Table
Write-Host "biome_decor_density: $(if ($Fails -eq 0) { 'PASS' } else { "FAIL ($Fails)" }) - table in $Out"
exit $(if ($Fails -eq 0) { 0 } else { 1 })
